/* ==========================================================================
   Web upload via GitHub API (admin only)
   - Click footer "管理" -> paste a GitHub token -> admin mode
   - Click "＋ 上传作品" -> pick a video/image -> uploads into the repo
   Token is stored in localStorage (only on your own browser).
   ========================================================================== */

(function () {
  'use strict';

  var OWNER = 'mxhz666';
  var REPO = 'mangxi';
  var BRANCH = 'main';
  var CATS = { '1': 'apparel', '2': 'brand', '3': 'chinese', '4': 'american', '5': 'ecommerce' };
  var CAT_LABEL = { apparel: '时尚服饰', brand: '品牌 TVC', chinese: '国风新中式', american: '复古美式', ecommerce: '电商创意短片' };

  var token = localStorage.getItem('gh_token') || '';
  var adminEntry = document.getElementById('adminEntry');
  var uploadBtn = document.getElementById('uploadBtn');
  if (!adminEntry || !uploadBtn) return;

  function setAdmin(on) {
    if (on) { document.body.classList.add('admin'); uploadBtn.style.display = 'inline-flex'; }
    else { document.body.classList.remove('admin'); uploadBtn.style.display = 'none'; }
  }
  if (token) setAdmin(true);

  function apiHeaders() { return { Authorization: 'token ' + token }; }
  function b64Encode(str) { return btoa(unescape(encodeURIComponent(str))); }
  function b64Decode(b64) { return decodeURIComponent(escape(atob(b64))); }
  function esc(s) { return String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"'); }

  function fileToBase64(file) {
    return new Promise(function (resolve, reject) {
      var r = new FileReader();
      r.onload = function () { resolve(String(r.result).split(',')[1]); };
      r.onerror = reject;
      r.readAsDataURL(file);
    });
  }

  function verifyToken(t) {
    return fetch('https://api.github.com/user', { headers: { Authorization: 'token ' + t } })
      .then(function (res) { return res.ok; })
      .catch(function () { return false; });
  }

  adminEntry.addEventListener('click', function () {
    if (token) {
      if (confirm('退出管理模式？')) { token = ''; localStorage.removeItem('gh_token'); setAdmin(false); }
      return;
    }
    var t = prompt('输入 GitHub Token：\n（在 GitHub Settings 里创建，只保存在你自己浏览器）');
    if (!t) return;
    verifyToken(t.trim()).then(function (ok) {
      if (ok) {
        token = t.trim();
        localStorage.setItem('gh_token', token);
        setAdmin(true);
        alert('已进入管理模式，可以上传作品了。');
      } else {
        alert('Token 无效');
      }
    });
  });

  function ghGet(path) {
    return fetch('https://api.github.com/repos/' + OWNER + '/' + REPO + '/contents/' + path, { headers: apiHeaders() })
      .then(function (res) {
        if (!res.ok) throw new Error('读取 ' + path + ' 失败（检查 Token 权限）');
        return res.json();
      });
  }
  function ghPut(path, contentB64, message, sha) {
    var body = { message: message, content: contentB64, branch: BRANCH };
    if (sha) body.sha = sha;
    var headers = apiHeaders();
    headers['Content-Type'] = 'application/json';
    return fetch('https://api.github.com/repos/' + OWNER + '/' + REPO + '/contents/' + path, {
      method: 'PUT', headers: headers, body: JSON.stringify(body)
    }).then(function (res) {
      if (!res.ok) return res.json().then(function (e) { throw new Error(e.message || '上传失败'); });
      return res.json();
    });
  }

  function buildWorksJs(arr) {
    var items = arr.map(function (w) {
      return '  { "title": "' + esc(w.title) + '", "cat": "' + esc(w.cat) + '", "src": "' + esc(w.src) + '", "meta": "' + esc(w.meta) + '" }';
    });
    return '/* AUTO-GENERATED by build.ps1 - edit works.json, not this file. */\nconst WORKS = [\n' + items.join(',\n') + '\n];\n';
  }

  function handleFile(file) {
    if (!token) { alert('请先点页脚「管理」输入 Token'); return; }
    if (file.size > 25 * 1024 * 1024) {
      if (!confirm('这个文件 ' + Math.round(file.size / 1024 / 1024) + 'MB，网页上传建议 <25MB，太大了可能失败。继续？')) return;
    }
    var catNum = prompt('选择分类：\n1 时尚服饰\n2 品牌 TVC\n3 国风新中式\n4 复古美式\n5 电商创意短片\n（输入 1-5，默认 2）', '2');
    if (catNum === null) return;
    var cat = CATS[catNum.trim()] || 'brand';
    var safe = file.name.replace(/[^\w.\-]+/g, '_');
    var path = 'assets/' + cat + '/' + Date.now().toString(36) + '-' + safe;

    uploadBtn.textContent = '上传中…';
    uploadBtn.disabled = true;

    fileToBase64(file)
      .then(function (dataB64) {
        return ghPut(path, dataB64, 'upload ' + safe);
      })
      .then(function () {
        return ghGet('js/works.js');
      })
      .then(function (cur) {
        var text = b64Decode(cur.content);
        var m = text.match(/const WORKS = (\[[\s\S]*?\]);/);
        var arr = [];
        if (m) { try { arr = JSON.parse(m[1]); } catch (e) { arr = []; } }
        var baseName = file.name.replace(/\.[^.]+$/, '');
        arr.push({ title: baseName, cat: cat, src: path, meta: (CAT_LABEL[cat] || '') + ' / - / ' + new Date().getFullYear() });
        return ghPut('js/works.js', b64Encode(buildWorksJs(arr)), 'add work ' + safe, cur.sha);
      })
      .then(function () {
        uploadBtn.textContent = '＋ 上传作品';
        uploadBtn.disabled = false;
        alert('上传成功！GitHub 正在更新，等 1-2 分钟后刷新网址就能看到。');
      })
      .catch(function (e) {
        uploadBtn.textContent = '＋ 上传作品';
        uploadBtn.disabled = false;
        alert('上传失败：' + (e && e.message ? e.message : e));
      });
  }

  uploadBtn.addEventListener('click', function () {
    if (!token) { alert('请先点页脚「管理」输入 Token'); return; }
    var input = document.createElement('input');
    input.type = 'file';
    input.accept = 'video/*,image/*';
    input.onchange = function () { if (input.files[0]) handleFile(input.files[0]); };
    input.click();
  });
})();
